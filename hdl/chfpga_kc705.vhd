		)
		port map(
			cpu_reset        => cpu_reset,
			GPIO_BUTTON0     => gpio_button0,
			gpio_led         => gpio_led,
			GPIO_DIP_SW      => gpio_dip_sw,

			clk10            => clk10,
			clk10_sel        => open,
			sysclk_p         => sysclk_p,
			sysclk_n         => sysclk_n,
			sfp_clk_p        => sfpclk_qo_p,
			sfp_clk_n        => sfpclk_qo_n,
