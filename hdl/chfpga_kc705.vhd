			user_mux_in      => (others => '0'),
			user_mux_oe      => open,


			-- GMII PHY Gigabit Ethernet Interface (Marvell Alaska 10-100-1000BASE-T PHY)

			phy_rxclk        => phy_rxclk,
			phy_txer         => phy_txer,
