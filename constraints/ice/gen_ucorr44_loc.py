#!/usr/bin/env python3
"""
Generate LOC constraints for ice_corr16 correlator BRAMs and DSPs.
Output: ice_physical_constraints_ucorr44.xdc (in same folder as this script).

Each ram_gen[R] has 2 RAMB36 (mem_reg_0, mem_reg_1) associated with
dsp_gen[2*R] and dsp_gen[2*R+1], each having dsp1 and dsp2.
corr_gen[0] -> upper region; corr_gen[1] -> lower region.
68 ram_gen per correlator, 4 columns x 17 rows.
Placement order: left to right (X 8..11), then bottom to top (increasing Y),
so logic that accesses close indices uses physically close DSP/RAM.
"""

import os

CORR_PREFIX = "chfpga0/CORRGEN.corr_sel_gen.ucorr44_case.ucorr44_array0"
NUM_RAM_GEN = 68
NUM_COLS = 4
NUM_ROWS = 17  # 4 * 17 = 68

# (corr_index, RAMB36_Y_base, DSP48_Y_base)
REGIONS = [
    (0, 45, 90),   # upper: corr_gen[0]
    (1, 0, 0),     # lower: corr_gen[1]
]


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(script_dir, "ice_physical_constraints_ucorr44.xdc")

    lines = [
        "# Auto-generated by gen_ucorr44_loc.py - do not edit by hand.",
        "# Regenerate with: python3 gen_ucorr44_loc.py",
        "",
        "# CORRELATOR BRAM / DSP LOC (ice_corr16)",
        "# Each ram_gen[R]: 2 RAMB36 + dsp_gen[2*R].dsp1/dsp2, dsp_gen[2*R+1].dsp1/dsp2",
        "",
    ]

    for C, ramb_base, dsp_base in REGIONS:
        for R in range(NUM_RAM_GEN):
            # Left to right (vary column), then bottom to top (vary row)
            col = 8 + (R % NUM_COLS)
            row = R // NUM_COLS
            ry = ramb_base + 2 * row
            ry1 = ry + 1
            dy = dsp_base + 4 * row
            dy1 = dy + 1
            dy2 = dy + 2
            dy3 = dy + 3
            d0 = 2 * R
            d1 = 2 * R + 1

            ram_path = f"{CORR_PREFIX}/corr_gen[{C}].corr0/corr0/ram_gen[{R}].ram0/xpm_memory_base_inst/gen_wr_a.gen_word_narrow"
            dsp_path = f"{CORR_PREFIX}/corr_gen[{C}].corr0/corr0/dsp_gen"

            lines.append(f"set_property LOC RAMB36_X{col}Y{ry} [get_cells {{{ram_path}.mem_reg_0}}]")
            lines.append(f"set_property LOC RAMB36_X{col}Y{ry1} [get_cells {{{ram_path}.mem_reg_1}}]")
            lines.append(f"set_property LOC DSP48_X{col}Y{dy} [get_cells {{{dsp_path}[{d0}].dsp1}}]")
            lines.append(f"set_property LOC DSP48_X{col}Y{dy1} [get_cells {{{dsp_path}[{d0}].dsp2}}]")
            lines.append(f"set_property LOC DSP48_X{col}Y{dy2} [get_cells {{{dsp_path}[{d1}].dsp1}}]")
            lines.append(f"set_property LOC DSP48_X{col}Y{dy3} [get_cells {{{dsp_path}[{d1}].dsp2}}]")
            lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Wrote {len(lines)} lines to {out_path}")


if __name__ == "__main__":
    main()
