#!/bin/bash
# Runs all the cases of the rawpack testbench (run.sh), one line of result for each.
# Needs the Vivado environment (source setenv.sh from the repository root). Exit status 1 if a case fails.
here=$(cd "$(dirname "$0")" && pwd)
# JOBS=<n> runs n cases at the same time (default 1), each one in its own work directory.
status=0
jobs=${JOBS:-1}
out=$(mktemp -d)
n=0
while read -r args; do
	n=$((n + 1))
	(
		result=$(WORK="$here/work/case$n" "$here/run.sh" $args 2>&1 | grep -E 'PASSED|Failure|Error|ERROR' | head -1)
		echo "[$args] ${result:-NO RESULT}" > "$out/$(printf %03d $n)"
	) &
	while [ "$(jobs -rp | wc -l)" -ge "$jobs" ]; do sleep 1; done
done <<CASES

